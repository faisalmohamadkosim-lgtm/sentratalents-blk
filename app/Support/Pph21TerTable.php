    public static function categoryForPtkp(string $ptkp): string
    {
        return match ($ptkp) {
            'TK/0', 'TK/1', 'K/0' => 'A',
            'TK/2', 'TK/3', 'K/1', 'K/2' => 'B',
            'K/3' => 'C',
            default => 'A',
        };
    }

    /** Tarif TER (desimal, misal 0.05 = 5%) untuk penghasilan bruto bulanan tertentu. */
    public static function rateForGross(string $category, float $grossMonthly): float
    {
        $table = self::table($category);
        foreach ($table as [$max, $rate]) {
            if ($max === null || $grossMonthly <= $max) {
                return $rate;
            }
        }
        return end($table)[1];
    }

